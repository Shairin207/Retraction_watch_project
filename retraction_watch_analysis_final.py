# Cell 36 — Advanced Helper Functions

def split_unique(value):
    if pd.isna(value):
        return []
    return sorted(set(x.strip() for x in str(value).split(";") if x.strip()))


def normalize_doi(value):
    if pd.isna(value):
        return pd.NA
    s = str(value).strip().lower()
    s = re.sub(r"^https?://(dx\.)?doi\.org/", "", s)
    s = re.sub(r"^doi:\s*", "", s)
    return s if s else pd.NA


def bh_fdr(p_values):
    p = np.asarray(p_values, dtype=float)
    n = len(p)
    if n == 0:
        return np.array([])
    order = np.argsort(p)
    ranked = p[order]
    adj = ranked * n / np.arange(1, n + 1)
    adj = np.minimum.accumulate(adj[::-1])[::-1]
    adj = np.clip(adj, 0, 1)
    out = np.empty(n)
    out[order] = adj
    return out


def rank_biserial_from_u(u_stat, n1, n2):
    # Positive values mean the first group tends to have larger values.
    return 2 * u_stat / (n1 * n2) - 1


def gini(values):
    x = np.asarray(values, dtype=float)
    x = x[np.isfinite(x) & (x >= 0)]
    if len(x) == 0 or x.sum() == 0:
        return np.nan
    x = np.sort(x)
    n = len(x)
    return (2 * np.sum((np.arange(1, n + 1)) * x) / (n * x.sum())) - (n + 1) / n


def two_prop_stats(x_old, n_old, x_new, n_new):
    p_old = x_old / n_old if n_old else np.nan
    p_new = x_new / n_new if n_new else np.nan
    pooled = (x_old + x_new) / (n_old + n_new)
    se = math.sqrt(max(pooled * (1 - pooled) * (1 / n_old + 1 / n_new), 0)) if n_old and n_new else np.nan
    z = (p_new - p_old) / se if se and np.isfinite(se) and se > 0 else np.nan
    pval = 2 * norm.sf(abs(z)) if np.isfinite(z) else np.nan
    rr = p_new / p_old if p_old and p_old > 0 else np.nan
    if x_old > 0 and x_new > 0 and np.isfinite(rr):
        se_log_rr = math.sqrt((1/x_new) - (1/n_new) + (1/x_old) - (1/n_old))
        lo = math.exp(math.log(rr) - 1.96 * se_log_rr)
        hi = math.exp(math.log(rr) + 1.96 * se_log_rr)
    else:
        lo = hi = np.nan
    return p_old, p_new, pval, rr, lo, hi

