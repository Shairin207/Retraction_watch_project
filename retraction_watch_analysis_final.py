def explode_semicolon(series):
    """Explode semicolon-delimited multi-value fields into clean individual values."""
    return (
        series.dropna()
        .astype(str)
        .str.split(";")
        .explode()
        .str.strip()
        .replace("", pd.NA)
        .dropna()
    )

def count_semicolon_items(value):
    """Count non-empty semicolon-delimited items."""
    if pd.isna(value):
        return 0
    return sum(bool(x.strip()) for x in str(value).split(";"))

def clean_subject_label(value):
    """Remove Retraction Watch subject code prefixes such as (B/T) or (SOC)."""
    return re.sub(r"^\([^)]+\)\s*", "", str(value)).strip()

def annotate_barh(ax, values):
    """Add compact value labels to horizontal bars."""
    for i, v in enumerate(values):
        ax.text(v, i, f" {int(v):,}", va="center", fontsize=8)

def pct(x):
    return f"{100*x:.1f}%"

